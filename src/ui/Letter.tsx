// מכתב הדרישה המעודכן: נבנה מנתוני המודל ומסעיפי ההסכם, מוכן להעתקה.
import { useEffect, useState } from 'react'
import { FOUR, type Row, med, tmuraRows } from '../lib/claim.ts'

const n1 = (x: number) => x.toLocaleString('he', { maximumFractionDigits: 1 })
const pct = (x: number) => Math.round(x * 100)

function build(rows: Row[]): string {
  const tw = rows.filter((r) => r.expanded && (r.lot === '102' || r.lot === '103'))
  const b101 = rows.filter((r) => r.expanded && r.lot === '101'), reg = rows.filter((r) => !r.expanded)
  const regTw = reg.filter((r) => r.lot === '102' || r.lot === '103'), above = regTw.filter((r) => r.floor > Math.max(...tw.map((x) => x.floor))).length
  const gap = Math.round((med(reg.map((r) => r.ppm)) / med(tw.map((r) => r.ppm)) - 1) * 100)
  return `תאריך: ________

לכבוד
מר אמיר לוטן, מנהל תחום פינוי בינוי
משולם לוינשטין הנדסה וקבלנות בע"מ

העתק: עו"ד רענן בשן, בא כוח הבעלים; נציגות הבעלים

מבלי לפגוע בזכויות

הנדון: פרויקט פינוי בינוי מתחם האצ"ל, רחובות. שיבוץ ארבע הדירות המורחבות במגדלים 102 ו־103

אנו, בעלי ארבע דירות מורחבות במתחם, פונים אליכם בעניין שיבוץ דירות התמורה שלנו.

1. העובדות

1.1 ארבע דירות התמורה שלנו שובצו בקומות ${tw.map((r) => r.floor).sort((a, b) => a - b).join(', ')}, מתוך ${tw[0].top} קומות, במגדלים 102 ו־103.
1.2 במונחי גובה הבניין, הדירות שלנו נמצאות ב־${pct(med(tw.map((r) => r.rel)))}% מגובהו. הדירות המורחבות שבבניין 101 נמצאות ב־${pct(med(b101.map((r) => r.rel)))}%, ודירות התמורה הרגילות ב־${pct(med(reg.map((r) => r.rel)))}%.
1.3 במגדלים עצמם, ${above} מתוך ${regTw.length} דירות התמורה הרגילות גבוהות מכל ארבע הדירות שלנו, והן מגיעות עד קומה ${Math.max(...reg.map((r) => r.floor))}.
1.4 בכל מגדל 133 דירות. בבניין 101 יש 73 דירות, ובבניין 104 יש 36.
1.5 אף אחת מארבע הדירות אינה פונה אל הגינה הציבורית. כולן פונות אל הרחובות ההיקפיים.
1.6 לא הוצעה לנו בחירה. לכל אחד מאיתנו הוקצתה דירה אחת, מסוימת.

2. ההסכם

2.1 סעיפים 10.5 עד 10.8 קובעים מנגנון של בחירה: חלוקת הבעלים לקבוצות לפי שטח הזכאות, ובחירה בתוך כל קבוצה לפי סדר הניקוד. קבוצה שיש בה דירה אחת מרוקנת את המנגנון מתוכנו.
2.2 סעיף 10.1 מחייב את החברה לפעול, ככל הניתן, לתמהיל שבו חלק מהדירות פונה לעורף וחלק לחזית.
2.3 בסוף סעיף 3 נקבע כי היזם אינו רשאי להעדיף מי מהבעלים, או לתת תמורה שאינה קבועה בהסכם, אלא באישור הנציגות מראש ובכתב או במסגרת הסדר. ככל שבעלי דירות מורחבות אחרים קיבלו אפשרות לבחור בין כמה דירות, או דירה מסוימת בהסכמה, אנו מבקשים לדעת על איזה אישור הדבר נשען.
2.4 סעיף 10.2 קובע כי שמאי הבעלים ישום את שווי כל הדירות הקיימות וייתן ניקוד לכל דירה.

3. בקשה לקבלת מסמכים

3.1 השומה המלאה לפי סעיף 10.2: שווי כל אחת מהדירות הקיימות, המקדמים שהופעלו על כל דירה, והניקוד שנגזר מהם.
3.2 טבלת הקצאת דירות התמורה, וחלוקת הבעלים לקבוצות לפי סעיף 10.5.
3.3 פרוטוקול מפגש בחירת הדירות לפי סעיף 10.9, ובו מה הוצע לכל בעלים.
3.4 אישורי הנציגות, ככל שניתנו, לשיבוץ דירות שלא במסגרת סדר הבחירה.

4. ההצעה שלנו

אנו מציעים הסדר מוסכם, באישור הנציגות כנדרש בהסכם, באחת משלוש הדרכים:

4.1 העמדת כמה דירות חלופיות לבחירתנו, בבניינים 101 ו־104 או בקומות גבוהות יותר במגדלים.
4.2 לחלופין, שדרוג לפי סעיף 20.1 בלי תשלום בגין הפרש הקומות: עד קומה 14 במגדלים, או עד קומה 9 בבניין 101.
4.3 לחלופין, למי שיישאר בדירתו, שדרוג במפרט בשווי ההפרש האמור.

5. הערכה ראשונית של הפער

לפי אומדן ראשוני שערכנו, ושאינו שומה, דירות התמורה הרגילות שוות כ־${gap}% יותר לכל מ"ר מהדירות שלנו, בשל הקומה. בכוונתנו לבקש שומה של דירות התמורה באותה שיטה שבה נערכה שומת סעיף 10.2, כדי למדוד את הפער במדויק.

6. נודה להתייחסותכם בתוך 14 ימים.

בכבוד רב,

${FOUR.map((o) => `${o.name} ____________`).join('\n')}`
}

export default function Letter() {
  const [rows, setRows] = useState<Row[] | null>(null)
  const [copied, setCopied] = useState(false)
  useEffect(() => { const id = setTimeout(() => setRows(tmuraRows()), 30); return () => clearTimeout(id) }, [])
  if (!rows) return <div className="value"><p className="hint">מכין את המכתב מנתוני המודל.</p></div>
  const text = build(rows)
  const copy = async () => {
    try { await navigator.clipboard.writeText(text); setCopied(true); setTimeout(() => setCopied(false), 2500) }
    catch { const el = document.getElementById('letter-text'); if (el) { const r = document.createRange(); r.selectNodeContents(el); const s = window.getSelection(); s?.removeAllRanges(); s?.addRange(r) } }
  }
  return (
    <div className="value letter">
      <header>
        <div>
          <div className="eyebrow">מכתב הדרישה המעודכן · טיוטה, לבדיקת עורך דין לפני שליחה</div>
          <h1>מכתב שנשען על <b>הבחירה שלא ניתנה</b>, ולא על הקומה לבדה</h1>
        </div>
        <p className="lede">המספרים במכתב נלקחים מהמודל, ומתעדכנים איתו.<br /><mark>הקומה מותרת בהסכם. מה שאינו מעוגן בו הוא שיבוץ בלי בחירה.</mark></p>
      </header>
      <section className="cols">
        <article className="paper">
          <div className="checks"><button id="letter-copy" type="button" className="act" onClick={copy}>{copied ? 'הועתק' : 'העתקת המכתב'}</button></div>
          <pre id="letter-text" dir="rtl">{text}</pre>
        </article>
        <div className="calc">
          <h2>מה שונה מהמכתב המקורי</h2>
          <ol className="verdict">
            <li><b>נוספו סעיפי ההסכם:</b> 10.1, 10.2, 10.5 עד 10.9, 20.1 ואיסור ההעדפה שבסוף סעיף 3.</li>
            <li><b>הטענה המרכזית הוחלפה.</b> במקום "קיבלנו קומה נמוכה": "לא ניתנה בחירה, בניגוד למנגנון שבהסכם".</li>
            <li><b>נוספו מספרים:</b> {pct(med(rows.filter((r) => r.expanded && (r.lot === '102' || r.lot === '103')).map((r) => r.rel)))}% מגובה הבניין, מול {pct(med(rows.filter((r) => r.expanded && r.lot === '101').map((r) => r.rel)))}% ו־{pct(med(rows.filter((r) => !r.expanded).map((r) => r.rel)))}%.</li>
            <li><b>הוסרה הטענה על "הכיוונים הפחות אטרקטיביים".</b> בשמש הדירות טובות מהממוצע, {n1(med(rows.filter((r) => r.expanded && (r.lot === '102' || r.lot === '103')).map((r) => r.winter)))} שעות בחורף. נשארה רק העובדה שהן פונות לרחוב ולא לגינה.</li>
            <li><b>הוסר המשפט "מגיע לנו קצת יותר".</b> הוא מחליש את טענת השוויון.</li>
            <li><b>נוספה בקשת מסמכים,</b> ובראשה שומת סעיף 10.2.</li>
            <li><b>ההצעה מנוסחת כהסדר באישור הנציגות,</b> כי ההסכם אוסר פיצוי בלי אישור כזה.</li>
          </ol>
          <h2>לפני השליחה</h2>
          <ol className="verdict">
            <li><b>ליישב את שתי הטבלאות</b> לגבי הבניין של שתי דירות קומה 4.</li>
            <li><b>לוודא את סעיף 1.6:</b> שלאף אחד מהארבעה לא הוצעה חלופה כלשהי.</li>
            <li><b>לבדוק מול עורך דין</b> שמתמחה בהתחדשות עירונית. זו טיוטה, לא ייעוץ משפטי.</li>
            <li><b>לשקול להוריד את סעיף 5</b> עד שתהיה שומה. אומדן ראשוני עלול להיתקף.</li>
          </ol>
          <p className="note"><b>עובדה:</b> הקומות, מספר הדירות והסעיפים. <b>הערכה:</b> האחוז שבסעיף 5 והפרשנות של הסעיפים. <b>הנחה:</b> התיאור שבסעיף 1.6 ובסעיף 2.3 נשען על המכתב המקורי, ולא אומת.</p>
        </div>
      </section>
    </div>
  )
}
